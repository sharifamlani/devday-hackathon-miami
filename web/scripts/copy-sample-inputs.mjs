#!/usr/bin/env node
/**
 * Copy the fictional sample inputs (data/sample_inputs/) into web/public/sample/
 * so "Try sample data" on the landing page can pre-load them, and write
 * manifest.json listing what was copied.
 *
 * NEVER copies answer_key.json (ground truth for tests; the ingest agent must
 * never see it) or the folder's _README.md. Re-run after new sample files land:
 *
 *   node scripts/copy-sample-inputs.mjs            (from web/)
 *
 * Exits non-zero if the source is missing or if an answer key ends up in the output.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../data/sample_inputs");
const target = path.resolve(here, "../public/sample");

const ALLOWED = new Set([".xlsx", ".docx", ".md", ".csv"]);
const NEVER = new Set(["answer_key.json", "_README.md"]);

if (!existsSync(source)) {
  console.error(`source not found: ${source}`);
  process.exit(1);
}

// Start clean so a removed sample file doesn't linger in public/.
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const files = readdirSync(source)
  .filter((name) => !NEVER.has(name) && ALLOWED.has(path.extname(name).toLowerCase()))
  .sort();

for (const name of files) copyFileSync(path.join(source, name), path.join(target, name));

const manifest = {
  _note: "Fictional sample inputs for the landing page's 'Try sample data'. Generated by web/scripts/copy-sample-inputs.mjs; do not edit.",
  files: files.map((name) => ({ name, bytes: statSync(path.join(target, name)).size })),
};
writeFileSync(path.join(target, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

const leaked = readdirSync(target).filter((name) => /answer[_-]?key/i.test(name));
if (leaked.length) {
  console.error(`refusing: answer key in output: ${leaked.join(", ")}`);
  process.exit(1);
}

console.log(`copied ${files.length} sample files to ${path.relative(process.cwd(), target)}:`);
for (const f of manifest.files) console.log(`  ${f.name}  ${f.bytes} B`);
