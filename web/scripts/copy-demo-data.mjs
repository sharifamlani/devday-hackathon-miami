#!/usr/bin/env node
/* eslint-disable no-console -- CLI script: it reports what it copied on stdout. */
/**
 * Copy the curated demo-data upload fixtures into public/demo-data/ for the
 * onboarding import action. Documentation files are deliberately excluded.
 * Run from web/ with: node scripts/copy-demo-data.mjs
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../demo-data");
const target = path.resolve(here, "../public/demo-data");
const ALLOWED = new Set([
  "team-call-list.csv",
  "tech-philanthropist-gifts.csv",
  "tech-philanthropist-profiles.txt",
]);

if (!existsSync(source)) {
  console.error(`source not found: ${source}`);
  process.exit(1);
}

const files = readdirSync(source).filter((name) => ALLOWED.has(name)).sort();
if (files.length !== ALLOWED.size) {
  console.error(`expected ${ALLOWED.size} demo-data fixtures, found ${files.length}`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
for (const name of files) {
  const contents = readFileSync(path.join(source, name), "utf8").replace(/\r\n/g, "\n");
  writeFileSync(path.join(target, name), contents);
}

const manifest = {
  _note: "Demo upload fixtures from demo-data/. Generated by web/scripts/copy-demo-data.mjs; do not edit.",
  files: files.map((name) => ({ name, bytes: statSync(path.join(target, name)).size })),
};
writeFileSync(path.join(target, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`copied ${files.length} demo-data fixtures to ${path.relative(process.cwd(), target)}:`);
for (const file of manifest.files) console.log(`  ${file.name}  ${file.bytes} B`);
